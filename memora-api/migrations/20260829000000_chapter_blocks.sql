-- Иллюстрации и структура главы.
--
-- Сплошной текст остаётся на месте: на нём держатся разбиение на слова,
-- озвучка, поиск по книге, адаптация под уровень и тренажёр «В контексте».
-- Ломать это ради картинок нельзя, поэтому структура кладётся РЯДОМ, а не
-- вместо: читалка показывает её, когда она есть, и текст, когда её нет.
--
-- Хранится разобранным списком блоков, а не разметкой страницы: чужая разметка
-- тянет за собой чужие стили и скрипты, а нам нужны только заголовки, абзацы,
-- списки и картинки.
ALTER TABLE book_chapters ADD COLUMN IF NOT EXISTS blocks JSONB NOT NULL DEFAULT '[]'::jsonb;
