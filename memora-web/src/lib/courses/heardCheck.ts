// Услышало ли распознавание то, что человек сказал.
//
// Вынесено из тренажёра отдельно, потому что это единственное место, где
// решается судьба попытки: засчитать её человеку в ошибку или признать, что
// не расслышали. Ошибка здесь дороже любой другой — она заставляет
// переучивать верно сказанное.

/**
 * Ниже этой уверенности распознавания попытка не оценивается.
 *
 * Порог намеренно мягкий: лучше изредка пропустить настоящую ошибку, чем
 * записать в ошибки верно сказанное слово — второе отбивает охоту заниматься.
 */
const LOW_CONFIDENCE = 0.55;

/** Выше этой вероятности «речи здесь нет» ответу верить нельзя. */
const NO_SPEECH = 0.6;
/** Ниже этой правдоподобности кусок обычно выдуман. */
const LOW_LOGPROB = -1.0;

const wordCount = (s: string) => s.trim().split(/\s+/).filter(Boolean).length;

/**
 * Услышало ли распознавание то, что человек сказал.
 *
 * Уверенности по словам мало: на тишине и шуме модель выдаёт связную ходовую
 * фразу и уверена в каждом её слове. Настоящая улика — длина: на двух
 * произнесённых словах приходит шесть, и это не ошибка произношения, а
 * досочинённый текст. Плюс два признака от самой модели: вероятность «речи
 * здесь нет» и правдоподобность куска.
 */
export function heardSomething(
  target: string,
  transcript: string,
  confidence: number,
  quality: { noSpeechProb: number; avgLogprob: number },
): boolean {
  if (quality.noSpeechProb > NO_SPEECH) return false;
  if (quality.avgLogprob !== 0 && quality.avgLogprob < LOW_LOGPROB) return false;

  // Вдвое длиннее ожидаемого плюс слово запаса: сказанное так не растягивается.
  const expected = wordCount(target);
  if (expected > 0 && wordCount(transcript) > expected * 2 + 1) return false;

  return !(confidence > 0 && confidence < LOW_CONFIDENCE);
}
