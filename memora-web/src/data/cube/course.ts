// Курс «Кубик Рубика»: послойный метод (метод новичка) — 7 этапов.
// Каждый этап: зачем он нужен, как узнать свой случай, алгоритм и что
// проверить в конце. Алгоритмы даны в стандартной нотации Сингмастера.

export interface CubeAlgorithm {
  /** Название случая: «жёлтая палка», «рыбка»… */
  name: string;
  /** Как понять, что у вас именно этот случай. */
  when: string;
  /** Ходы в нотации. */
  moves: string;
  /** Что сделать с собранным кубом, чтобы показать случай наглядно. */
  setup?: string;
  /** Пояснение к самому движению. */
  note?: string;
}

export interface CubeStep {
  id: string;
  n: number;
  title: string;
  goal: string;
  /** Пояснение простым языком, абзацами. */
  text: string[];
  algorithms: CubeAlgorithm[];
  /** Как проверить себя перед переходом дальше. */
  check: string;
}

