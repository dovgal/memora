/** Как показывать упражнение: анимированная цель, таймер или счётчик. */
export type VisionKind = 'track' | 'timer' | 'reps';

/** Траектория для упражнений слежения. */
export type Path =
  | 'horizontal' | 'vertical' | 'diagonal1' | 'diagonal2'
  | 'circle' | 'infinity' | 'zigzag' | 'spiral' | 'nearFar';

export interface VisionExercise {
  id: string;
  emoji: string;
  title: string;
  /** Одна строка — что делаем, детским языком. */
  short: string;
  /** Шаги выполнения. */
  steps: string[];
  /** Зачем это нужно — для ребёнка. */
  why: string;
  kind: VisionKind;
  path?: Path;
  /** Секунды для timer/track, повторы для reps. */
  seconds?: number;
  reps?: number;
  /** Скорость движения цели, сек на один проход. */
  speed?: number;
  /** Предупреждение, если есть. */
  care?: string;
}

